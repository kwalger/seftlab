export type LegoBrickColor =
  | 'blue'
  | 'emerald'
  | 'amber'
  | 'purple'
  | 'cyan'
  | 'indigo'
  | 'rose'
  | 'slate';

export type LegoTaskLayout = 'tower' | 'match' | 'buckets' | 'equation';

export interface LegoBrick {
  id: string;
  label: string;
  sublabel?: string;
  tag?: string;
  color: LegoBrickColor;
  numericValue?: number;
}

export interface LegoSlot {
  id: string;
  title: string;
  prompt: string;
  groupId?: string;
  correctBrickId: string;
  /** عند مهام التصنيف في مجموعات، يسمح بأي بطاقة صحيحة ينتمي لنفس المجموعة */
  acceptedBrickIds?: string[];
  explanation: string;
}

export interface LegoSlotGroup {
  id: string;
  title: string;
  subtitle?: string;
  color: LegoBrickColor;
  /** لوضع المعادلة والحساب الرقمي: تحديد الجانب الأيمن أو الأيسر أو الإجمالي */
  equationSide?: 'left' | 'right' | 'plus' | 'minus' | 'result';
}

